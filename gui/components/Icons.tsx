/*
  Icons in the wallet's geometry: a 24px grid, no fill, 2px strokes, round caps
  and joins. Colour is inherited (currentColor); the shape carries the meaning.
  The asset and direction icons are the wallet's own (src/icons/assetIcons.tsx).
*/

type IconProps = React.SVGProps<SVGSVGElement> & { size?: number };

function Svg({ size = 18, children, ...props }: IconProps & { children: React.ReactNode }) {
  return (
    <svg
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      {...props}
    >
      {children}
    </svg>
  );
}

